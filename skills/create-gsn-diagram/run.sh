from __future__ import annotations

import argparse
import json
import sys
import textwrap
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Optional
from xml.etree import ElementTree as ET


# ── GSN node types ────────────────────────────────────────────────────────

@dataclass
class GSNNode:
    id: str
    label: str
    node_type: str  # Goal | Strategy | Solution | Context | Assumption
    # SACM extensions
    description: str = ""
    taxonomy_mind: list[str] = field(default_factory=list)  # Mind tags
    taxonomy_heart: list[str] = field(default_factory=list)  # Heart tags
    oscal_ref: str = ""  # Reference to OSCAL AR finding
    lean4_ref: str = ""  # Reference to Lean4 proof
    control_id: str = ""  # SPARTA/NIST control ID
    confidence: float = 0.0  # 0.0-1.0

@dataclass
class GSNEdge:
    src: str
    dst: str
    label: str = ""
    edge_type: str = "SupportedBy"  # SupportedBy | InContextOf | Challenges

@dataclass
class GSNGraph:
    nodes: list[GSNNode] = field(default_factory=list)
    edges: list[GSNEdge] = field(default_factory=list)
    metadata: dict[str, str] = field(default_factory=dict)

    def add(self, node: GSNNode) -> None:
        self.nodes.append(node)

    def link(self, src: str, dst: str, label: str = "", edge_type: str = "SupportedBy") -> None:
        self.edges.append(GSNEdge(src=src, dst=dst, label=label, edge_type=edge_type))


# ── DOT shapes per GSN type ──────────────────────────────────────────────

GSN_SHAPES: dict[str, dict[str, str]] = {
    "Goal":       {"shape": "box",           "style": "filled", "fillcolor": "#E8F0FE", "color": "#1A73E8"},
    "Strategy":   {"shape": "parallelogram", "style": "filled", "fillcolor": "#FFF3E0", "color": "#E65100"},
    "Solution":   {"shape": "circle",        "style": "filled", "fillcolor": "#E8F5E9", "color": "#2E7D32"},
    "Context":    {"shape": "box",           "style": "filled,rounded", "fillcolor": "#F3E5F5", "color": "#7B1FA2"},
    "Assumption": {"shape": "ellipse",       "style": "filled,dashed", "fillcolor": "#FFF9C4", "color": "#F9A825"},
}


# ── SACM XML namespaces (OMG SACM 2.2) ───────────────────────────────────

SACM_NS = {
    "sacm": "http://www.omg.org/spec/SACM/2.2/sacm",
    "base": "http://www.omg.org/spec/SACM/2.2/base",
    "arg": "http://www.omg.org/spec/SACM/2.2/argumentation",
    "arti": "http://www.omg.org/spec/SACM/2.2/artifact",
    "term": "http://www.omg.org/spec/SACM/2.2/terminology",
    "xsi": "http://www.w3.org/2001/XMLSchema-instance",
}

# GSN type → SACM element mapping
GSN_TO_SACM = {
    "Goal":       "arg:Claim",
    "Strategy":   "arg:ArgumentReasoning",
    "Solution":   "arti:ArtifactReference",
    "Context":    "arg:InformationElement",
    "Assumption": "arg:InformationElement",
}


# ── SACM XML export ─────────────────────────────────────────────────────

def graph_to_sacm(g: GSNGraph, title: str = "Assurance Case") -> str:
    """Export GSN graph to OMG SACM 2.2 XML format.

    SACM (Structured Assurance Case Metamodel) is the OMG standard
    for machine-readable assurance cases. This enables:
    - Tool interoperability
    - Automated argument validation
    - Integration with OSCAL evidence
    - Linking to Lean4 formal proofs
    """
    # Register namespaces for clean output
    for prefix, uri in SACM_NS.items():
        ET.register_namespace(prefix, uri)

    # Root element: AssuranceCasePackage
    root = ET.Element(
        f"{{{SACM_NS['sacm']}}}AssuranceCasePackage",
        attrib={
            f"{{{SACM_NS['xsi']}}}schemaLocation": "http://www.omg.org/spec/SACM/2.2/sacm SACM.xsd",
            "gid": f"pkg_{uuid.uuid4().hex[:8]}",
            "name": title,
        }
    )

    # Metadata
    meta = ET.SubElement(root, f"{{{SACM_NS['base']}}}description")
    meta.text = f"Generated by /create-gsn-diagram at {datetime.now(timezone.utc).isoformat()}"

    # Add framework metadata from graph
    if g.metadata.get("framework"):
        fw_meta = ET.SubElement(root, f"{{{SACM_NS['base']}}}implementationConstraint")
        fw_meta.set("content", f"framework={g.metadata['framework']}")

    # ArgumentPackage container
    arg_pkg = ET.SubElement(root, f"{{{SACM_NS['arg']}}}ArgumentPackage")
    arg_pkg.set("gid", f"arg_{uuid.uuid4().hex[:8]}")
    arg_pkg.set("name", f"{title} Argument")

    # Create SACM elements for each GSN node
    node_elements: dict[str, ET.Element] = {}
    for node in g.nodes:
        sacm_type = GSN_TO_SACM.get(node.node_type, "arg:Claim")
        ns_key = sacm_type.split(":")[0]
        local_name = sacm_type.split(":")[1]

        elem = ET.SubElement(arg_pkg, f"{{{SACM_NS[ns_key]}}}{local_name}")
        elem.set("gid", node.id)
        elem.set("name", node.label[:100])  # SACM name limit

        # Description element
        if node.description or node.label:
            desc = ET.SubElement(elem, f"{{{SACM_NS['base']}}}description")
            desc.text = node.description or node.label

        # Taxonomy as implementationConstraint (Context nodes)
        if node.taxonomy_mind:
            mind_elem = ET.SubElement(elem, f"{{{SACM_NS['base']}}}implementationConstraint")
            mind_elem.set("content", f"taxonomy:mind={','.join(node.taxonomy_mind)}")

        if node.taxonomy_heart:
            heart_elem = ET.SubElement(elem, f"{{{SACM_NS['base']}}}implementationConstraint")
            heart_elem.set("content", f"taxonomy:heart={','.join(node.taxonomy_heart)}")

        # Control ID reference
        if node.control_id:
            ctrl_elem = ET.SubElement(elem, f"{{{SACM_NS['base']}}}implementationConstraint")
            ctrl_elem.set("content", f"control_id={node.control_id}")

        # OSCAL reference (for Solution nodes)
        if node.oscal_ref:
            oscal_elem = ET.SubElement(elem, f"{{{SACM_NS['arti']}}}externalReference")
            oscal_elem.set("location", node.oscal_ref)
            oscal_elem.set("type", "OSCAL-AR")

        # Lean4 proof reference (for Solution nodes)
        if node.lean4_ref:
            lean_elem = ET.SubElement(elem, f"{{{SACM_NS['arti']}}}externalReference")
            lean_elem.set("location", node.lean4_ref)
            lean_elem.set("type", "Lean4-Proof")

        # Confidence level
        if node.confidence > 0:
            conf_elem = ET.SubElement(elem, f"{{{SACM_NS['base']}}}implementationConstraint")
            conf_elem.set("content", f"confidence={node.confidence:.2f}")

        node_elements[node.id] = elem

    # Create SACM relationships for edges
    for edge in g.edges:
        # SupportedBy → AssertedInference
        # InContextOf → AssertedContext
        # Challenges → AssertedChallenge
        if edge.edge_type == "SupportedBy":
            rel_type = "AssertedInference"
        elif edge.edge_type == "InContextOf":
            rel_type = "AssertedContext"
        elif edge.edge_type == "Challenges":
            rel_type = "AssertedChallenge"
        else:
            rel_type = "AssertedInference"

        rel = ET.SubElement(arg_pkg, f"{{{SACM_NS['arg']}}}{rel_type}")
        rel.set("gid", f"rel_{edge.src}_{edge.dst}")

        # Source reference
        src_ref = ET.SubElement(rel, f"{{{SACM_NS['arg']}}}source")
        src_ref.set("href", f"#{edge.src}")

        # Target reference
        tgt_ref = ET.SubElement(rel, f"{{{SACM_NS['arg']}}}target")
        tgt_ref.set("href", f"#{edge.dst}")

        if edge.label:
            desc = ET.SubElement(rel, f"{{{SACM_NS['base']}}}description")
            desc.text = edge.label

    # Pretty print
    ET.indent(root, space="  ")
    return ET.tostring(root, encoding="unicode", xml_declaration=True)


# ── DOT emitter ──────────────────────────────────────────────────────────

def graph_to_dot(g: GSNGraph, title: str = "Assurance Case") -> str:
    lines = [
        "digraph assurance_case {",
        '  rankdir=TB;',
        f'  label="{title}";',
        '  labelloc=t;',
        '  fontname="Helvetica";',
        '  node [fontname="Helvetica", fontsize=10];',
        '  edge [fontname="Helvetica", fontsize=9];',
        "",
    ]
    for n in g.nodes:
        attrs = GSN_SHAPES.get(n.node_type, {"shape": "box"})
        attr_str = ", ".join(f'{k}="{v}"' for k, v in attrs.items())
        label = n.label.replace('"', '\\"')
        lines.append(f'  "{n.id}" [label="{label}", {attr_str}];')
    lines.append("")
    for e in g.edges:
        lbl = f' [label="{e.label}"]' if e.label else ""
        lines.append(f'  "{e.src}" -> "{e.dst}"{lbl};')
    lines.append("}")
    return "\n".join(lines)


# ── Sample / dry-run graph ───────────────────────────────────────────────

def build_sample_graph(control_id: str = "AC-1") -> GSNGraph:
    """Build a sample GSN graph with taxonomy metadata for dry-run testing."""
    g = GSNGraph()
    g.metadata["framework"] = "NIST-800-171"
    g.metadata["generated"] = datetime.now(timezone.utc).isoformat()

    # Goal: the top-level claim
    g.add(GSNNode(
        "G1",
        f"G1: {control_id} Access Control Policy",
        "Goal",
        description=f"The system implements {control_id} access control policy requirements",
        control_id=control_id,
        taxonomy_mind=["Harden", "Detect"],  # SPARTA tactical tags
        confidence=0.85,
    ))

    # Strategy: how we argue for the goal
    g.add(GSNNode(
        "S1",
        "S1: Verify via evidence chain",
        "Strategy",
        description="Demonstrate compliance through deterministic evidence + formal proof",
    ))

    # Solution: evidence artifacts
    g.add(GSNNode(
        "Sn1",
        "Sn1: QRA evidence",
        "Solution",
        description="Question-Response-Action from /create-evidence-case",
        oscal_ref=f"oscal-ar://findings/{control_id.lower()}_qra",
        confidence=0.92,
    ))
    g.add(GSNNode(
        "Sn2",
        "Sn2: Formal proof",
        "Solution",
        description="Lean4 proof of control satisfaction",
        lean4_ref=f"lean4://proofs/{control_id.lower()}_theorem",
        confidence=0.99,
    ))

    # Context: categorical metadata (taxonomy goes here per SACM)
    g.add(GSNNode(
        "C1",
        "C1: NIST 800-171 framework",
        "Context",
        description="NIST SP 800-171 Rev 2 compliance framework",
        taxonomy_mind=["Harden"],  # Framework-level tactical scope
    ))
    g.add(GSNNode(
        "C2",
        "C2: Tactical scope",
        "Context",
        description="Mind tags: Harden, Detect — this control hardens access and detects violations",
        taxonomy_mind=["Harden", "Detect"],
    ))

    # Edges
    g.link("G1", "S1", edge_type="SupportedBy")
    g.link("S1", "Sn1", "supports", edge_type="SupportedBy")
    g.link("S1", "Sn2", "supports", edge_type="SupportedBy")
    g.link("G1", "C1", "in context of", edge_type="InContextOf")
    g.link("G1", "C2", "tactical scope", edge_type="InContextOf")
    return g


# ── Memory-first queries (no direct ArangoDB access) ─────────────────────
import subprocess
from pathlib import Path

MEMORY_RUN = str(Path(__file__).resolve().parent.parent / "memory" / "run.sh")


def _memory_sample(collection: str, limit: int = 100, filter_expr: str = "", fields: str = "") -> list[dict]:
    """Query via /memory sample — fail loud, never fallback to direct DB."""
    cmd = [MEMORY_RUN, "sample", "--collection", collection, "--limit", str(limit)]
    if filter_expr:
        cmd += ["--filter", filter_expr]
    if fields:
        cmd += ["--fields", fields]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        print(f"FATAL: /memory unavailable: {result.stderr}", file=sys.stderr)
        sys.exit(1)
    return json.loads(result.stdout).get("items", [])


def _memory_recall(query: str, scope: str = "sparta", collections: str = "", k: int = 10) -> list[dict]:
    """Query via /memory recall — fail loud, never fallback to direct DB."""
    cmd = [MEMORY_RUN, "recall", "--q", query, "--scope", scope, "--k", str(k)]
    if collections:
        cmd += ["--collections", collections]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        print(f"FATAL: /memory unavailable: {result.stderr}", file=sys.stderr)
        sys.exit(1)
    return json.loads(result.stdout).get("items", [])


def build_graph_from_db(control_id: str) -> GSNGraph:
    """Query /memory for a control and its evidence chain with taxonomy metadata."""
    g = GSNGraph()

    # Fetch the control document via memory sample
    controls = _memory_sample(
        "sparta_controls", limit=1,
        filter_expr=f'doc.control_id=="{control_id}"',
    )
    if not controls:
        print(f"error: control '{control_id}' not found via /memory", file=sys.stderr)
        sys.exit(1)

    ctrl = controls[0]
    fw = ctrl.get("source_framework") or ctrl.get("framework", "Unknown")
    g.metadata["framework"] = fw
    g.metadata["control_id"] = control_id
    g.metadata["generated"] = datetime.now(timezone.utc).isoformat()

    # Extract taxonomy from control
    mind_tags = ctrl.get("mind", [])
    if isinstance(mind_tags, str):
        mind_tags = [mind_tags]

    # Goal: top-level claim with taxonomy
    goal_label = f"G1: {ctrl.get('control_id', control_id)} {ctrl.get('title', '')}"
    g.add(GSNNode(
        "G1",
        goal_label.strip(),
        "Goal",
        description=ctrl.get("description", ""),
        control_id=control_id,
        taxonomy_mind=mind_tags,
        confidence=ctrl.get("confidence", 0.0),
    ))

    # Context: framework
    g.add(GSNNode(
        "C1",
        f"C1: {fw} framework",
        "Context",
        description=f"Compliance framework: {fw}",
    ))
    g.link("G1", "C1", "in context of", edge_type="InContextOf")

    # Context: tactical scope (Mind tags)
    if mind_tags:
        g.add(GSNNode(
            "C2",
            f"C2: Tactical scope: {', '.join(mind_tags)}",
            "Context",
            description=f"SPARTA Mind taxonomy: {', '.join(mind_tags)}",
            taxonomy_mind=mind_tags,
        ))
        g.link("G1", "C2", "tactical scope", edge_type="InContextOf")

    # Strategy: evidence verification
    g.add(GSNNode(
        "S1",
        "S1: Verify via evidence chain",
        "Strategy",
        description="Demonstrate compliance through QRA evidence + formal proofs",
    ))
    g.link("G1", "S1", edge_type="SupportedBy")

    # Evidence — use memory recall to find related QRAs
    evidence = _memory_recall(
        f"evidence for control {control_id}",
        scope="sparta", collections="sparta_qra", k=10,
    )
    for i, ev in enumerate(evidence, 1):
        nid = f"Sn{i}"
        title = ev.get("question") or ev.get("title") or ev.get("problem") or ev.get("_key", "evidence")
        label = f"{nid}: {title[:60]}..."
        ntype = "Solution"
        if ev.get("type") == "assumption":
            ntype = "Assumption"

        # Extract evidence metadata
        ev_mind = ev.get("mind", [])
        if isinstance(ev_mind, str):
            ev_mind = [ev_mind]

        g.add(GSNNode(
            nid,
            label,
            ntype,
            description=ev.get("answer", ""),
            taxonomy_mind=ev_mind,
            oscal_ref=f"oscal-ar://findings/{ev.get('_key', '')}",
            lean4_ref=ev.get("formal_proof", ""),
            confidence=ev.get("scores", {}).get("bm25", 0.0),
        ))
        g.link("S1", nid, "supports", edge_type="SupportedBy")

    # Fallback: if no evidence found, note it
    if not evidence:
        g.add(GSNNode(
            "Sn1",
            "Sn1: (no evidence found)",
            "Solution",
            description="No QRA evidence found for this control",
        ))
        g.link("S1", "Sn1", "supports", edge_type="SupportedBy")

    return g


def build_graph_for_framework(framework: str) -> GSNGraph:
    """Build a combined GSN graph for all controls under a framework."""
    g = GSNGraph()

    controls = _memory_sample(
        "controls", limit=500,
        filter_expr=f'doc.framework=="{framework}"',
    )
    if not controls:
        print(f"error: no controls found for framework '{framework}' via /memory", file=sys.stderr)
        sys.exit(1)

    # Sort by control_id
    controls.sort(key=lambda c: c.get("control_id", ""))

    # Top-level goal
    g.add(GSNNode("G0", f"G0: {framework} Compliance", "Goal"))
    g.add(GSNNode("C0", f"C0: {framework} framework", "Context"))
    g.link("G0", "C0", "in context of")

    for ci, ctrl in enumerate(controls, 1):
        gid = f"G{ci}"
        sid = f"S{ci}"
        cid = ctrl.get("control_id", f"CTRL-{ci}")
        title = ctrl.get("title", "")
        g.add(GSNNode(gid, f"{gid}: {cid} {title}".strip(), "Goal"))
        g.link("G0", gid)
        g.add(GSNNode(sid, f"{sid}: Verify {cid}", "Strategy"))
        g.link(gid, sid)

    return g


# ── Render via graphviz Python package ───────────────────────────────────

def render_graph(dot_src: str, output: str) -> None:
    import graphviz as gv  # type: ignore[import-untyped]
    fmt = "png" if output.endswith(".png") else "svg"
    # graphviz.Source renders from DOT text
    src = gv.Source(dot_src, format=fmt)
    # render writes <output>.<fmt>, we want exact path
    out_base = output.rsplit(".", 1)[0] if "." in output else output
    src.render(filename=out_base, cleanup=True)
    print(f"rendered: {output}")


# ── CLI ──────────────────────────────────────────────────────────────────

def main() -> None:
    parser = argparse.ArgumentParser(
        description="GSN assurance case diagrams from compliance graph (DOT/SVG + SACM XML)",
    )
    sub = parser.add_subparsers(dest="command", required=True)

    # render (DOT → SVG/PNG)
    p_render = sub.add_parser("render", help="Render GSN diagram to SVG/PNG")
    p_render.add_argument("--control",   type=str, default=None)
    p_render.add_argument("--framework", type=str, default=None)
    p_render.add_argument("--output",    type=str, default=None)
    p_render.add_argument("--dry-run",   action="store_true")

    # export-dot (DOT notation to stdout)
    p_dot = sub.add_parser("export-dot", help="Export raw DOT notation to stdout")
    p_dot.add_argument("--control",   type=str, default=None)
    p_dot.add_argument("--framework", type=str, default=None)
    p_dot.add_argument("--dry-run",   action="store_true")

    # export-sacm (OMG SACM 2.2 XML export)
    p_sacm = sub.add_parser("export-sacm", help="Export OMG SACM 2.2 XML to stdout/file")
    p_sacm.add_argument("--control",   type=str, default=None)
    p_sacm.add_argument("--framework", type=str, default=None)
    p_sacm.add_argument("--output",    type=str, default=None, help="Output file (default: stdout)")
    p_sacm.add_argument("--dry-run",   action="store_true")

    args = parser.parse_args()

    # Validate: need exactly one of --control or --framework
    if not args.control and not args.framework:
        parser.error("provide --control or --framework")
    if args.control and args.framework:
        parser.error("provide --control or --framework, not both")

    # Build the graph
    if args.dry_run:
        ctrl_id = args.control or "AC-1"
        graph = build_sample_graph(ctrl_id)
        title = f"Assurance Case: {ctrl_id} (dry-run)"
    elif args.control:
        graph = build_graph_from_db(args.control)
        title = f"Assurance Case: {args.control}"
    else:
        graph = build_graph_for_framework(args.framework)
        title = f"Assurance Case: {args.framework}"

    # Export based on command
    if args.command == "export-dot":
        dot_src = graph_to_dot(graph, title=title)
        print(dot_src)
        return

    if args.command == "export-sacm":
        sacm_xml = graph_to_sacm(graph, title=title)
        if args.output:
            with open(args.output, "w", encoding="utf-8") as f:
                f.write(sacm_xml)
            print(f"SACM XML written to: {args.output}", file=sys.stderr)
        else:
            print(sacm_xml)
        return

    # render (SVG/PNG)
    dot_src = graph_to_dot(graph, title=title)
    output = args.output
    if not output:
        name = args.control or args.framework or "assurance_case"
        output = f"{name}_gsn.svg"

    render_graph(dot_src, output)


if __name__ == "__main__":
    main()
