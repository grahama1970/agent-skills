"""create-gsn-diagram: GSN diagrams from ArangoDB compliance graph.

Supports:
- DOT/graphviz rendering (SVG, PNG)
- OMG SACM 2.2 XML export (machine-readable assurance cases)
- Taxonomy context integration (Mind tags → SACM Context nodes)
