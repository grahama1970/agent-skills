from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[3]
RUN_SH = ROOT / "skills" / "review-code" / "run.sh"
SCRATCH_BUNDLE = Path("/home/graham/workspace/experiments/pi-mono/local/docs/scratch.md")
ENV_FLAG = "REVIEW_CODE_LIVE_PINGPONG_E2E"


def _json_from_stdout(stdout: str) -> dict[str, Any]:
    stripped = stdout.strip()
    if not stripped:
        raise AssertionError("expected JSON on stdout, got empty output")
    for start in [0, *[idx for idx, ch in enumerate(stripped) if ch == "{"]]:
        try:
            loaded = json.loads(stripped[start:])
            if isinstance(loaded, dict):
                return loaded
        except json.JSONDecodeError:
            continue
    raise AssertionError(f"could not parse JSON from stdout: {stdout[:500]}")


def _events(out: Path) -> list[dict[str, Any]]:
    path = out / "events.jsonl"
    assert path.is_file(), f"missing events file: {path}"
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line]


def _artifact_text(root: Path) -> str:
    parts: list[str] = []
    for path in root.rglob("*"):
        if path.is_file() and path.suffix in {".json", ".jsonl", ".md", ".txt"}:
            parts.append(path.read_text(encoding="utf-8", errors="replace"))
    return "\n".join(parts)


def test_live_ping_pong_gpt55_high_review_bundle() -> None:
    if os.environ.get(ENV_FLAG) != "1":
        print(f"skipped: set {ENV_FLAG}=1 to run the live GPT-5.5 ping-pong E2E")
        return
    assert SCRATCH_BUNDLE.is_file(), f"missing real review bundle: {SCRATCH_BUNDLE}"
    assert "scratch.md" in str(SCRATCH_BUNDLE)

    with tempfile.TemporaryDirectory(prefix="review-code-ping-pong-live-") as temp_dir:
        out = Path(temp_dir) / "ping-pong-run"
        env = {**os.environ, "NO_COLOR": "1"}
        proc = subprocess.run(
            [
                str(RUN_SH),
                "ping-pong",
                "--file",
                str(SCRATCH_BUNDLE),
                "--reviewer",
                "ask:gpt-5.5",
                "--reasoning",
                "high",
                "--rounds",
                "1",
                "--idle-timeout",
                "900",
                "--max-wall-clock",
                "3600",
                "--output-dir",
                str(out),
                "--json",
            ],
            text=True,
            capture_output=True,
            env=env,
            timeout=3900,
        )
        assert proc.returncode == 0, proc.stderr + "\n" + proc.stdout
        status = _json_from_stdout(proc.stdout)
        assert status["status"] in {"completed", "waiting_for_parent", "needs_attention"}
        assert status["requested_model"] == "gpt-5.5"
        assert status["requested_reasoning"] == "high"
        assert status["bundle_path"] == str(SCRATCH_BUNDLE)

        events = _events(out)
        event_names = [event["event"] for event in events]
        assert "run_started" in event_names
        assert "reviewer_started" in event_names
        assert any(name in event_names for name in {"reviewer_completed", "clarification_requested", "recommendation", "error"})

        artifact_paths = status.get("artifact_paths") or {}
        assert artifact_paths.get("bundle") == str(SCRATCH_BUNDLE)
        assert any("round_1" in key for key in artifact_paths), artifact_paths
        text = _artifact_text(out)
        assert "gpt-5.5" in text
        assert "high" in text
        assert "Merge recommendation" in text or "Merge-blocking" in text or "SAFE_" in text or "CHANGES_REQUESTED" in text or "clarification" in text.lower()


if __name__ == "__main__":
    test_live_ping_pong_gpt55_high_review_bundle()
    print("ping_pong_live_e2e passed")
