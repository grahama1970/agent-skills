"""Named pause/wait macros for Chatterbox render text.

The agent writes [pause:<name>] by context (e.g. [pause:weight] before a hard
landing). This resolves each named token to the numeric [pause:<ms>ms] token
the best-practices-chatterbox pause compiler already understands, so silence is
still generated by the service, not simulated. Durations are human-verified by
ear (same authority as emotion macros); this module only maps name -> ms.

Fail-closed: an unknown macro name raises, so a typo never gets spoken aloud.
Numeric [pause:750ms] tokens and everything else pass through untouched.

Run `python3 pauses.py` for the self-check.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

_NAMED = re.compile(r"\[pause:([a-z_]+)\]", re.I)


def load_macros(path: str | Path) -> dict[str, int]:
    """Load {macro_name: ms} from the pause_macros.json fixture."""
    data = json.loads(Path(path).read_text())
    macros = data.get("macros", data)
    return {str(k).lower(): int(v["ms"] if isinstance(v, dict) else v) for k, v in macros.items()}


def resolve_pause_macros(text: str, macros: dict[str, int]) -> str:
    """Expand [pause:<name>] -> [pause:<ms>ms]. Unknown name -> ValueError."""
    def _sub(m: re.Match) -> str:
        name = m.group(1).lower()
        if name in macros:
            return f"[pause:{macros[name]}ms]"
        raise ValueError(f"unknown_pause_macro:{name}")
    return _NAMED.sub(_sub, text)


def demo() -> None:
    macros = {"beat": 300, "weight": 1100}
    assert resolve_pause_macros("Wait. [pause:beat] Okay.", macros) == "Wait. [pause:300ms] Okay.", "beat"
    assert resolve_pause_macros("[pause:weight] I'm sorry.", macros) == "[pause:1100ms] I'm sorry.", "weight"
    # numeric tokens and prose untouched
    assert resolve_pause_macros("Hold [pause:750ms] there.", macros) == "Hold [pause:750ms] there."
    assert resolve_pause_macros("No pause here.", macros) == "No pause here."
    # unknown name fails closed
    try:
        resolve_pause_macros("Bad [pause:nope] one.", macros)
        raise AssertionError("expected ValueError for unknown macro")
    except ValueError as e:
        assert "unknown_pause_macro:nope" in str(e)
    # loads real fixture
    real = load_macros(Path(__file__).resolve().parents[1] / "fixtures/pause_macros.json")
    assert real["weight"] == 1100 and real["breath"] == 500, real
    print("pauses.py self-check: PASS")


if __name__ == "__main__":
    demo()
