#!/usr/bin/env node

import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");
const RUN = join(ROOT, "run.sh");

const tests = [];
const test = (name, fn) => tests.push({ name, fn });

function sha256(text) {
  return "sha256:" + createHash("sha256").update(text).digest("hex");
}

function sandbox() {
  const dir = mkdtempSync(join(tmpdir(), "unlazy-receipt-test-"));
  return {
    dir,
    write(rel, text) {
      const path = join(dir, rel);
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
      return path;
    },
    cleanup() { rmSync(dir, { recursive: true, force: true }); },
  };
}

function buildFixture(s) {
  const goal = '{"schema":"example.goal.v1","goal":"prove receipt binding"}\n';
  const ledger = '# Gates\n\n- [x] G1: receipt binding works\n  EVIDENCE: generated by test\n';
  const lock = '{"schema":"unlazy.gates_lock.v1","approved":true}\n';
  const artifact = '{"schema":"example.artifact.v1","status":"PASS"}\n';
  s.write("GOAL.json", goal);
  s.write("GATES.md", ledger);
  s.write(".agent/contracts/GATES.lock.json", lock);
  s.write(".agent/runs/run-1/artifact.json", artifact);
  return {
    acceptance_ref: {
      schema: "unlazy.acceptance_ref.v1",
      goal_path: "GOAL.json",
      goal_sha256: sha256(goal),
      ledger_path: "GATES.md",
      ledger_sha256: sha256(ledger),
      lock_path: ".agent/contracts/GATES.lock.json",
      lock_sha256: sha256(lock),
      required_gate_ids: ["G1"],
    },
    artifact_sha256: sha256(artifact),
  };
}

function runReceiptCheck(s, receiptRel) {
  try {
    const out = execFileSync("bash", [RUN, "receipt-check", "--project-root", s.dir, "--json", join(s.dir, receiptRel)], {
      cwd: ROOT,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "pipe"],
    });
    return { code: 0, out };
  } catch (error) {
    return {
      code: error.status ?? 1,
      out: String(error.stdout || "") + String(error.stderr || ""),
    };
  }
}

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function assertHas(text, needle) {
  assert(text.includes(needle), "missing " + JSON.stringify(needle) + "\n--- got ---\n" + text);
}

test("receipt-check accepts project-bound receipt with matching acceptance ref", () => {
  const s = sandbox();
  try {
    const fixture = buildFixture(s);
    s.write(".agent/runs/run-1/receipt.json", JSON.stringify({
      schema: "herdr.work_receipt.v1",
      acceptance_ref: fixture.acceptance_ref,
      global_goal_state: "NOT_MET",
      gate_receipts: [
        {
          gate_id: "G1",
          path: ".agent/runs/run-1/artifact.json",
          sha256: fixture.artifact_sha256,
        },
      ],
    }, null, 2) + "\n");
    const result = runReceiptCheck(s, ".agent/runs/run-1/receipt.json");
    assert(result.code === 0, "expected pass, got " + result.code + "\n" + result.out);
    assertHas(result.out, '"status": "PASS"');
    assertHas(result.out, '"unlazy.receipt_check.v1"');
  } finally { s.cleanup(); }
});

test("receipt-check rejects forged global completion from a non-watchdog receipt", () => {
  const s = sandbox();
  try {
    const fixture = buildFixture(s);
    s.write(".agent/runs/run-1/receipt.json", JSON.stringify({
      schema: "herdr.work_receipt.v1",
      acceptance_ref: fixture.acceptance_ref,
      global_goal_state: "ACHIEVED_WITH_RECEIPT",
    }, null, 2) + "\n");
    const result = runReceiptCheck(s, ".agent/runs/run-1/receipt.json");
    assert(result.code === 1, "expected fail, got " + result.code + "\n" + result.out);
    assertHas(result.out, "claims global completion");
  } finally { s.cleanup(); }
});

test("receipt-check rejects acceptance ref hash drift", () => {
  const s = sandbox();
  try {
    const fixture = buildFixture(s);
    fixture.acceptance_ref.ledger_sha256 = "sha256:" + "0".repeat(64);
    s.write(".agent/runs/run-1/receipt.json", JSON.stringify({
      schema: "tau.terminal_receipt.v1",
      acceptance_ref: fixture.acceptance_ref,
      global_goal_state: "NOT_MET",
    }, null, 2) + "\n");
    const result = runReceiptCheck(s, ".agent/runs/run-1/receipt.json");
    assert(result.code === 1, "expected fail, got " + result.code + "\n" + result.out);
    assertHas(result.out, "ledger hash mismatch");
  } finally { s.cleanup(); }
});

test("receipt-check rejects referenced artifacts outside the project root", () => {
  const s = sandbox();
  try {
    const fixture = buildFixture(s);
    s.write(".agent/runs/run-1/receipt.json", JSON.stringify({
      schema: "herdr.work_receipt.v1",
      acceptance_ref: fixture.acceptance_ref,
      global_goal_state: "NOT_MET",
      gate_receipts: [
        {
          gate_id: "G1",
          path: "../outside.json",
          sha256: "sha256:" + "1".repeat(64),
        },
      ],
    }, null, 2) + "\n");
    const result = runReceiptCheck(s, ".agent/runs/run-1/receipt.json");
    assert(result.code === 1, "expected fail, got " + result.code + "\n" + result.out);
    assertHas(result.out, "cannot contain traversal");
  } finally { s.cleanup(); }
});

let passed = 0;
const failures = [];
for (const item of tests) {
  try {
    item.fn();
    passed += 1;
    console.log("ok   " + item.name);
  } catch (error) {
    failures.push(item.name + ": " + error.message);
    console.log("FAIL " + item.name);
    console.log("     " + error.message);
  }
}

if (failures.length) {
  console.log("receipt-check tests FAILED (" + passed + "/" + tests.length + ")");
  process.exit(1);
}
console.log("receipt-check tests ok (" + passed + "/" + tests.length + ")");
