ORPHEUS_MIN_EXAMPLES = 50
ORPHEUS_RECOMMENDED_EXAMPLES = 300
ORPHEUS_SAMPLE_RATE = 24000
EVENT_WORDS_BY_TAG = {
    "laugh": ("laugh", "laughs", "laughing", "laughed"),
    "chuckle": ("chuckle", "chuckles", "chuckling", "chuckled"),
    "sigh": ("sigh", "sighs", "sighing", "sighed"),
    "cough": ("cough", "coughs", "coughing", "coughed"),
    "sniffle": ("sniffle", "sniffles", "sniffling", "sniffled"),
    "groan": ("groan", "groans", "groaning", "groaned"),
    "yawn": ("yawn", "yawns", "yawning", "yawned"),
    "gasp": ("gasp", "gasps", "gasping", "gasped"),
}


def _load_orpheus_audio_example(path: Path) -> dict:
    """Build a datasets Audio example without torchcodec."""
    import numpy as np
    import soundfile as sf

    array, sampling_rate = sf.read(str(path), always_2d=False)
    if array.ndim > 1:
        array = array.mean(axis=1)
    if sampling_rate != ORPHEUS_SAMPLE_RATE:
        raise ValueError(f"Expected {ORPHEUS_SAMPLE_RATE} Hz, got {sampling_rate} for {path}")
    return {"array": np.asarray(array, dtype=np.float32), "sampling_rate": ORPHEUS_SAMPLE_RATE}



def _convert_audio_for_orpheus(src: Path, dest: Path) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(
        ["ffmpeg", "-y", "-i", str(src), "-ac", "1", "-ar", str(ORPHEUS_SAMPLE_RATE), str(dest)],
        check=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )


def _tag_names(tags: list[str]) -> list[str]:
    names: list[str] = []
    for tag in tags:
        name = str(tag).strip().lower().strip("<>")
        if name in EVENT_WORDS_BY_TAG and name not in names:
            names.append(name)
    return names


def _literal_tag_asr_check_clip(clip_path: Path, tags: list[str], allowed_spoken_text: str = "") -> dict:
    """Reject generated clips where the audio speaks the tag word literally."""
    expected_tags = _tag_names(tags)
    if not expected_tags:
        return {"status": "PASS", "expected_tags": []}
    try:
        from lib.transcribe import transcribe_clip

        transcript, confidence = transcribe_clip(clip_path)
    except Exception as exc:
        return {
            "status": "FAIL",
            "reason": "literal_tag_check_unavailable",
            "expected_tags": expected_tags,
            "error": str(exc),
        }

    lowered = transcript.lower()
    allowed_lowered = allowed_spoken_text.lower()
    spoken = []
    for tag in expected_tags:
        words = [
            word
            for word in EVENT_WORDS_BY_TAG[tag]
            if not re.search(rf"\b{re.escape(word)}\b", allowed_lowered)
        ]
        if words and any(re.search(rf"\b{re.escape(word)}\b", lowered) for word in words):
            spoken.append(tag)
    return {
        "status": "FAIL" if spoken else "PASS",
        "reason": "literal_tag_spoken" if spoken else "",
        "expected_tags": expected_tags,
        "spoken_literal_tags": spoken,
        "asr_transcript": transcript,
        "asr_confidence": confidence,
    }


