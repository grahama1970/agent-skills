#!/usr/bin/env python3
from __future__ import annotations

import argparse
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from persona_dream_nava_lane.io_utils import write_json  # noqa: E402
from persona_dream_nava_lane.media import find_new_mp4s  # noqa: E402


def main() -> None:
    parser = argparse.ArgumentParser(description="Run local NAVA inference for the persona-dream NAVA lane.")
    parser.add_argument("--nava-repo", required=True, help="Path to cloned ernie-research/NAVA repo.")
    parser.add_argument("--data-file", required=True, help="NAVA JSONL generated by build_nava_inputs.py.")
    parser.add_argument("--out-dir", required=True)
    parser.add_argument("--ckpt", default="NAVA_fp8.safetensors")
    parser.add_argument("--config", default="configs/nava.yaml")
    parser.add_argument("--width", type=int, default=1280)
    parser.add_argument("--height", type=int, default=704)
    parser.add_argument("--frames", type=int, default=37)
    parser.add_argument("--fps", type=int, default=24)
    parser.add_argument("--steps", type=int, default=50)
    parser.add_argument("--gen-turn", type=int, default=1)
    parser.add_argument("--use-sp", action="store_true")
    parser.add_argument("--nproc-per-node", type=int, default=8)
    parser.add_argument("--single-gpu", action="store_true", help="Use python inference_nava.py instead of torchrun.")
    parser.add_argument("--fp8", action="store_true", help="Pass --weight_dtype fp8_e4m3fn.")
    parser.add_argument("--t5-offload", action="store_true", help="Pass --t5_offload if supported by your NAVA checkout.")
    parser.add_argument("--dry-run", action="store_true", help="Write command manifest without running.")
    args = parser.parse_args()

    nava_repo = Path(args.nava_repo).expanduser().resolve()
    data_file = Path(args.data_file).expanduser().resolve()
    out_dir = Path(args.out_dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    if not nava_repo.exists():
        raise FileNotFoundError(nava_repo)
    if not data_file.exists():
        raise FileNotFoundError(data_file)

    infer_py = nava_repo / "inference_nava.py"
    if not infer_py.exists():
        raise FileNotFoundError(f"Missing inference_nava.py under {nava_repo}")

    base_args = [
        str(infer_py),
        "--config",
        args.config,
        "--ckpt",
        args.ckpt,
        "--out_dir",
        str(out_dir),
        "--data_format",
        "json",
        "--data_file",
        str(data_file),
        "--width",
        str(args.width),
        "--height",
        str(args.height),
        "--frames",
        str(args.frames),
        "--fps",
        str(args.fps),
        "--steps",
        str(args.steps),
        "--save_sample",
        "--gen_turn",
        str(args.gen_turn),
    ]

    if args.use_sp and not args.single_gpu:
        base_args.append("--use_sp")

    if args.fp8:
        base_args.extend(["--weight_dtype", "fp8_e4m3fn"])

    if args.t5_offload:
        base_args.append("--t5_offload")

    if args.single_gpu:
        cmd = [sys.executable, *base_args]
    else:
        cmd = [
            "torchrun",
            "--nnodes=1",
            f"--nproc_per_node={args.nproc_per_node}",
            "--master_addr=127.0.0.1",
            "--master_port=29507",
            *base_args,
        ]

    manifest = {
        "schema_version": "persona_dream_nava_run_manifest.v0.1",
        "nava_repo": str(nava_repo),
        "data_file": str(data_file),
        "out_dir": str(out_dir),
        "command": cmd,
        "dry_run": args.dry_run,
    }
    write_json(out_dir / "nava_run_manifest.json", manifest)

    print("+ " + " ".join(cmd))
    if args.dry_run:
        print(f"[dry-run] wrote {out_dir / 'nava_run_manifest.json'}")
        return

    started_at = time.time()
    completed = subprocess.run(cmd, cwd=str(nava_repo), check=False, text=True)
    new_mp4s = find_new_mp4s(out_dir, started_at)

    result = {
        **manifest,
        "returncode": completed.returncode,
        "new_mp4s": [str(p) for p in new_mp4s],
        "primary_output_video": str(new_mp4s[0]) if new_mp4s else None,
    }
    write_json(out_dir / "nava_run_result.json", result)

    if completed.returncode != 0:
        raise SystemExit(completed.returncode)

    print(f"[nava] wrote {out_dir / 'nava_run_result.json'}")
    if new_mp4s:
        print(f"[nava] primary_output_video={new_mp4s[0]}")
    else:
        print("[nava] no new mp4 found; inspect NAVA output directory.")


if __name__ == "__main__":
    main()
