#!/usr/bin/env python3
"""Canonical cross-provider output contract: template selection and broadcast.

Purpose
    One template governs how every agent reports results. This module selects
    the active template and installs it as a managed block inside each
    provider's always-on instruction file plus every Claude output style.

Inputs
    templates/*.md      candidate contracts; exactly one is active
    active.json         records the active template name
    Provider targets    resolved from PROVIDERS plus discovered output styles

Outputs
    A managed block delimited by BEGIN_MARKER/END_MARKER in every target.
    Backups under ~/.local/state/agent-skills/output-contract-backups.

Failure modes
    Missing or unknown template -> typer.Exit(2), nothing written.
    Drift in `check` -> exit 1, nothing written (check never mutates).
    An unreadable target is reported and skipped; other targets still sync.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from datetime import UTC, datetime
from enum import StrEnum
from pathlib import Path

import typer
from loguru import logger

SKILL_DIR = Path(__file__).resolve().parent
REPO_ROOT = SKILL_DIR.parents[1]
TEMPLATE_DIR = SKILL_DIR / "templates"
ACTIVE_FILE = SKILL_DIR / "active.json"
STYLE_DIR = REPO_ROOT / "output-styles"
BACKUP_DIR = Path.home() / ".local" / "state" / "agent-skills" / "output-contract-backups"

BEGIN_MARKER = "<!-- BEGIN agent-skills:output-contract -->"
END_MARKER = "<!-- END agent-skills:output-contract -->"
GENERATED_NOTE = (
    "<!-- Generated by skills/writing-style — edit the template, "
    "then run skills/writing-style/run.sh apply -->"
)
DEFAULT_TEMPLATE = "clear-technical"


class SyncState(StrEnum):
    """Closed vocabulary for one target's outcome."""

    OK = "ok"
    DRIFT = "drift"
    UPDATED = "updated"
    UNREADABLE = "unreadable"


@dataclass(frozen=True, slots=True)
class Target:
    """One file that must carry the managed block."""

    path: Path
    label: str

    @property
    def display(self) -> str:
        home = str(Path.home())
        return str(self.path).replace(home, "~", 1)


@dataclass(frozen=True, slots=True)
class TargetResult:
    """Outcome for one target after a check or apply pass."""

    target: Target
    state: SyncState
    detail: str = ""


# Each provider reads only its own filename. Verified 2026-08-14 by a
# controlled test: with both files present Claude Code read CLAUDE.md and
# ignored AGENTS.md. Never assume one provider falls back to another's file.
PROVIDERS: tuple[tuple[str, str], ...] = (
    (".claude/CLAUDE.md", "Claude Code"),
    (".codex/AGENTS.md", "Codex"),
    (".gemini/GEMINI.md", "Gemini CLI"),
    (".cursor/rules/output-contract.mdc", "Cursor"),
)

app = typer.Typer(add_completion=False, help="Cross-provider output contract broadcast.")


def template_path(name: str) -> Path:
    return TEMPLATE_DIR / f"{name}.md"


def available_templates() -> list[str]:
    if not TEMPLATE_DIR.is_dir():
        return []
    return sorted(p.stem for p in TEMPLATE_DIR.glob("*.md"))


def active_template() -> str:
    """Name of the active template, defaulting when unset or corrupt."""
    if ACTIVE_FILE.is_file():
        try:
            name = json.loads(ACTIVE_FILE.read_text(encoding="utf-8")).get("template")
        except (OSError, json.JSONDecodeError):
            logger.error("active.json unreadable; falling back to {}", DEFAULT_TEMPLATE)
            name = None
        if isinstance(name, str) and template_path(name).is_file():
            return name
    return DEFAULT_TEMPLATE


def set_active_template(name: str) -> None:
    ACTIVE_FILE.write_text(
        json.dumps({"template": name, "updated_at": datetime.now(UTC).isoformat()}, indent=2) + "\n",
        encoding="utf-8",
    )


def resolve_targets() -> list[Target]:
    """Provider files plus every discovered output style.

    Styles are globbed rather than listed so adding one needs no code edit.
    """
    targets = [Target(Path.home() / rel, label) for rel, label in PROVIDERS]
    if STYLE_DIR.is_dir():
        targets += [Target(p, "Claude output style") for p in sorted(STYLE_DIR.glob("*.md"))]
    return targets


def render_block(contract: str) -> str:
    return f"{BEGIN_MARKER}\n{GENERATED_NOTE}\n{contract.rstrip()}\n{END_MARKER}"


def strip_block(text: str) -> str:
    """Remove any managed block, keeping provider-specific content intact."""
    pattern = re.compile(
        re.escape(BEGIN_MARKER) + r".*?" + re.escape(END_MARKER) + r"\n?",
        re.DOTALL,
    )
    return pattern.sub("", text)


def desired_content(existing: str, contract: str) -> str:
    """Provider content, then one blank line, then exactly one managed block."""
    preserved = strip_block(existing).rstrip()
    block = render_block(contract)
    return f"{preserved}\n\n{block}\n" if preserved else f"{block}\n"


def backup(target: Target) -> Path | None:
    """Copy a non-empty target outside every directory a provider scans."""
    if not target.path.is_file() or target.path.stat().st_size == 0:
        return None
    BACKUP_DIR.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now(UTC).strftime("%Y%m%dT%H%M%S")
    dest = BACKUP_DIR / f"{target.path.name}.bak-{stamp}"
    dest.write_text(target.path.read_text(encoding="utf-8"), encoding="utf-8")
    return dest


def sync_target(target: Target, contract: str, *, apply: bool) -> TargetResult:
    """Bring one target in line with the contract, or report its drift."""
    try:
        existing = target.path.read_text(encoding="utf-8") if target.path.is_file() else ""
    except OSError as exc:
        logger.error("cannot read {}: {}", target.path, exc)
        return TargetResult(target, SyncState.UNREADABLE, str(exc))

    wanted = desired_content(existing, contract)
    if existing == wanted:
        return TargetResult(target, SyncState.OK)
    if not apply:
        return TargetResult(target, SyncState.DRIFT)

    try:
        target.path.parent.mkdir(parents=True, exist_ok=True)
        backup(target)
        target.path.write_text(wanted, encoding="utf-8")
    except OSError as exc:
        logger.error("cannot write {}: {}", target.path, exc)
        return TargetResult(target, SyncState.UNREADABLE, str(exc))
    return TargetResult(target, SyncState.UPDATED)


def load_contract(name: str) -> str:
    path = template_path(name)
    if not path.is_file():
        typer.echo(f"unknown template '{name}'. available: {', '.join(available_templates()) or 'none'}", err=True)
        raise typer.Exit(2)
    return path.read_text(encoding="utf-8")


def run_sync(name: str, *, apply: bool) -> int:
    contract = load_contract(name)
    results = [sync_target(t, contract, apply=apply) for t in resolve_targets()]
    for result in results:
        hint = "" if result.state is not SyncState.DRIFT else "  (run: run.sh apply)"
        typer.echo(f"{result.state.value:<10} {result.target.display}{hint}")
    failed = [r for r in results if r.state in (SyncState.DRIFT, SyncState.UNREADABLE)]
    return 1 if failed else 0


@app.command("list")
def list_command() -> None:
    """List available templates and mark the active one."""
    names = available_templates()
    if not names:
        typer.echo(f"no templates in {TEMPLATE_DIR}", err=True)
        raise typer.Exit(2)
    current = active_template()
    for name in names:
        typer.echo(f"{'* ' if name == current else '  '}{name}")


@app.command("use")
def use_command(template: str = typer.Argument(..., help="Template name to activate.")) -> None:
    """Select the active template. Does not broadcast; run apply next."""
    load_contract(template)
    set_active_template(template)
    typer.echo(f"active template: {template}\nrun 'run.sh apply' to broadcast it")


@app.command("show")
def show_command(
    template: str = typer.Option("", "--template", help="Template to print. Defaults to active."),
) -> None:
    """Print a template's contract text."""
    typer.echo(load_contract(template or active_template()), nl=False)


@app.command("targets")
def targets_command() -> None:
    """List every file the active template is broadcast into."""
    for target in resolve_targets():
        typer.echo(f"{target.label:<22} {target.display}")


@app.command("check")
def check_command() -> None:
    """Report drift without changing anything. Exit 1 if any target differs."""
    raise typer.Exit(run_sync(active_template(), apply=False))


@app.command("apply")
def apply_command() -> None:
    """Install the active template's block into every target."""
    raise typer.Exit(run_sync(active_template(), apply=True))


if __name__ == "__main__":
    app()
