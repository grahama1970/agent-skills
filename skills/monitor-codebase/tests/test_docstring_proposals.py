def test_ast_changing_patch_attempt_rolls_back(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    source = write_module(tmp_path, "api.py", "def load_user(user_id):\n    return user_id\n")
    candidate = approve(by_name(candidates_for(tmp_path, source), "load_user"), "Return the user identifier.")
    monkeypatch.setattr(autofix_docstrings, "docstring_line", lambda _docstring, indent: f"{indent}x = 1\n")
    receipt = autofix_docstrings.apply_candidate(tmp_path, candidate)
    assert receipt["applied"] is False
    assert any("non_docstring_ast_changed" in error for error in receipt["errors"])
    assert "x = 1" not in source.read_text(encoding="utf-8")
