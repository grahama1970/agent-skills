def test_multiline_signature_and_decorator_apply_preserves_ast(tmp_path: Path) -> None:
    source = write_module(
        tmp_path,
        "decorated.py",
        """
        def deco(fn):
            return fn

        @deco
        def public_api(
            first,
            second,
        ):
            return first + second
        """,
    )
    candidate = approve(by_name(candidates_for(tmp_path, source), "public_api"), "Return the combined value.")
    receipt = autofix_docstrings.apply_candidate(tmp_path, candidate)
    assert receipt["applied"] is True
    assert '"""Return the combined value."""' in source.read_text(encoding="utf-8")


def test_nested_function_and_class_are_addressable(tmp_path: Path) -> None:
    source = write_module(
        tmp_path,
        "nested.py",
        """
        class Outer:
            def method(self, value):
                def inner(extra):
                    return value + extra
                return inner(1)
        """,
    )
    candidates = candidates_for(tmp_path, source)
    assert by_name(candidates, "Outer")["symbol"]["symbol_kind"] == "class"
    assert by_name(candidates, "Outer.method")["symbol"]["symbol_kind"] == "function"
    assert by_name(candidates, "Outer.method.inner")["symbol"]["symbol_kind"] == "function"


def test_stale_proposal_after_source_edit_is_rejected(tmp_path: Path) -> None:
    source = write_module(tmp_path, "api.py", "def load_user(user_id):\n    return user_id\n")
    candidate = approve(by_name(candidates_for(tmp_path, source), "load_user"), "Return the user identifier.")
    source.write_text("def load_user(user_id):\n    return str(user_id)\n", encoding="utf-8")
    receipt = autofix_docstrings.apply_candidate(tmp_path, candidate)
    assert receipt["applied"] is False
    assert "stale_source_hash" in receipt["errors"]
    assert '"""' not in source.read_text(encoding="utf-8")


def test_model_outage_or_malformed_response_makes_no_change(tmp_path: Path) -> None:
    source = write_module(tmp_path, "api.py", "def load_user(user_id):\n    return user_id\n")
