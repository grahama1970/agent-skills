# CLI
# ---------------------------------------------------------------------------

def main() -> None:
    import typer

    app = typer.Typer(help="Cross-project quality checks for monitor-codebase.")

    @app.command()
    def scan(
        project: str = typer.Argument(help="Project directory to scan"),
        json_output: bool = typer.Option(False, "--json", help="Output as JSON"),
    ) -> None:
        result = scan_project(project)
        if json_output:
            print(json.dumps(result, indent=2))
        else:
            total = result["total_violations"]
            print(f"\n=== Quality Check: {result['project']} ===")
            print(f"Total violations: {total}")
            if result["by_rule"]:
                print("\nBy rule:")
                for rule, count in sorted(result["by_rule"].items()):
                    print(f"  {rule}: {count}")
            if total > 0:
                print(f"\nTop violations:")
                for v in result["violations"][:30]:
                    print(f"  [{v['rule']}] {v.get('file', '?')}: {v['message']}")
                if total > 30:
                    print(f"  ... and {total - 30} more")

