def _check_handwritten_tests(root: Path) -> list[dict[str, Any]]:
    """Detect test files without test-lab markers."""
    violations = []
    for py_file in _iter_py_files(root):
        if not py_file.name.startswith("test_"):
            continue
        try:
            content = py_file.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        if not any(marker in content for marker in _TEST_LAB_MARKERS):
            violations.append({
                "rule": "handwritten-tests",
                "file": str(py_file.relative_to(root)),
                "line": 0,
                "message": "Test file has no test-lab markers — use /test-lab generate",
                "severity": "warn",
            })
    return violations


def _check_mock_only_tests(root: Path) -> list[dict[str, Any]]:
    """Detect projects where ALL tests use mocks with no integration tests."""
    test_files = [f for f in _iter_py_files(root) if f.name.startswith("test_")]
    if not test_files:
        return []

    has_sanity = (root / "sanity.sh").exists()
    all_mocked = True
    for tf in test_files:
        try:
            content = tf.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue
        if not any(p in content for p in [
            "unittest.mock", "MagicMock", "AsyncMock", "@patch", "mock.patch",
        ]):
            all_mocked = False
            break

    if all_mocked and not has_sanity:
        return [{
            "rule": "mock-only-tests",
            "file": str(root),
            "line": 0,
            "message": "All tests use mocks but no sanity.sh — mock tests pass while real service may be broken",
            "severity": "warn",
        }]
    return []


def _check_typescript_practices(root: Path) -> list[dict[str, Any]]:
    """Detect conservative TypeScript/React best-practice violations."""
    violations = []
    any_pattern = re.compile(r"(:\s*any\b|as\s+any\b|<any>)")
    inline_import_pattern = re.compile(r"\bimport\s*\(")
    barrel_import_pattern = re.compile(r"from\s+['\"](?:\.\.?/)?(?:index)?['\"]")

    for source_file in _iter_files(root, _TYPESCRIPT_SUFFIXES):
        if source_file.name.endswith(".d.ts"):
            continue

        content = _read_text(source_file)
        if not content:
            continue

        rel = str(source_file.relative_to(root))
        for match in any_pattern.finditer(content):
            violations.append({
                "rule": "typescript-any-type",
                "file": rel,
                "line": _line_number(content, match.start()),
                "message": "TypeScript uses `any`; prefer a concrete type or `unknown` with narrowing",
                "severity": "warn",
            })

        for match in inline_import_pattern.finditer(content):
            violations.append({
                "rule": "typescript-inline-import",
                "file": rel,
                "line": _line_number(content, match.start()),
                "message": "Inline import detected; use top-level imports for agent-readable dependencies",
                "severity": "warn",
            })

        if source_file.suffix in {".tsx", ".jsx"}:
            for match in barrel_import_pattern.finditer(content):
                violations.append({
                    "rule": "typescript-barrel-import",
                    "file": rel,
                    "line": _line_number(content, match.start()),
                    "message": "Barrel import obscures component/module boundaries",
                    "severity": "info",
                })

    return violations


def _check_rust_practices(root: Path) -> list[dict[str, Any]]:
    """Detect conservative Rust best-practice violations."""
    violations = []
    unwrap_pattern = re.compile(r"\.unwrap\s*\(")
    debug_output_pattern = re.compile(r"\b(?:dbg!|eprintln!)\s*\(")

    for source_file in _iter_files(root, _RUST_SUFFIXES):
        rel = str(source_file.relative_to(root))
        if "/tests/" in f"/{rel}/" or rel.endswith("_test.rs"):
            continue

        content = _read_text(source_file)
        if not content:
            continue

        for match in unwrap_pattern.finditer(content):
            violations.append({
                "rule": "rust-unwrap",
                "file": rel,
                "line": _line_number(content, match.start()),
                "message": "Rust production code uses `.unwrap()`; return context or document an invariant",
                "severity": "warn",
            })

        for match in debug_output_pattern.finditer(content):
            violations.append({
                "rule": "rust-debug-output",
                "file": rel,
                "line": _line_number(content, match.start()),
                "message": "Rust debug output detected; use tracing or a deliberate user-facing output path",
                "severity": "warn",
            })

    return violations


def _is_prompt_file(path: Path, root: Path) -> bool:
    """Return whether a text file is likely to be an LLM prompt template."""
    if path.suffix not in _PROMPT_SUFFIXES:
        return False

    rel_parts = tuple(part.lower() for part in path.relative_to(root).parts)
    if set(rel_parts) & _PROMPT_DIR_NAMES:
        return True
    return "prompt" in path.stem.lower()


def _has_prompt_output_format(content: str) -> bool:
    """Detect explicit prompt output contracts without trying to parse prose."""
    lowered = content.lower()
    return any(
        marker in lowered
        for marker in (
            "output format",
            "output schema",
            "return only",
            "json schema",
            "pydantic",
            "schema:",
            "exact schema",
        )
    )


def _has_review_payload(path: Path) -> bool:
    """Check for a nearby review payload consumed by review-prompt."""
    review_dir = path.parent / "review"
    if not review_dir.is_dir():
        return False

    stem = path.stem.replace("_system", "").replace("_user", "")
    payloads = list(review_dir.glob("*_payload.txt"))
    if not payloads:
        return False
    return any(stem in payload.stem for payload in payloads) or len(payloads) == 1


def _check_prompt_practices(root: Path) -> list[dict[str, Any]]:
    """Detect best-practices-prompt issues in prompt templates."""
    violations = []
    word_pattern = re.compile(
        r"\b(" + "|".join(re.escape(word) for word in _PROMPT_WEASEL_WORDS) + r")\b",
        re.IGNORECASE,
    )

    for prompt_file in _iter_files(root, _PROMPT_SUFFIXES):
        if not _is_prompt_file(prompt_file, root):
            continue

        content = _read_text(prompt_file)
        if not content:
            continue

        rel = str(prompt_file.relative_to(root))
        if "# RATIONALE" not in content[:800]:
            violations.append({
                "rule": "prompt-missing-rationale",
                "file": rel,
                "line": 1,
                "message": "Prompt template is missing a best-practices-prompt rationale header",
                "severity": "warn",
            })

        for match in word_pattern.finditer(content):
            violations.append({
                "rule": "prompt-weasel-word",
                "file": rel,
                "line": _line_number(content, match.start()),
                "message": f"Prompt uses vague word `{match.group(0)}`; replace it with concrete criteria",
                "severity": "info",
            })

        if not _has_prompt_output_format(content):
            violations.append({
                "rule": "prompt-missing-output-format",
                "file": rel,
                "line": 1,
                "message": "Prompt template does not name an exact output format or schema",
                "severity": "warn",
            })

        if "_system" in prompt_file.stem or "_user" in prompt_file.stem:
            if not _has_review_payload(prompt_file):
                violations.append({
                    "rule": "prompt-missing-review-payload",
                    "file": rel,
                    "line": 1,
                    "message": "Prompt pair is missing a review/*_payload.txt file for review-prompt audit",
                    "severity": "warn",
                })

    return violations


