def _should_skip(path: Path) -> bool:
    parts = path.parts
    if set(parts) & _EXCLUDE_DIRS:
        return True
    # Catch .venv-batch, .venv_old, .venv.bak and any other venv variant
    return any(part.startswith(".venv") for part in parts)


def _iter_py_files(root: Path) -> list[Path]:
    return [f for f in root.rglob("*.py") if not _should_skip(f)]


def _iter_files(root: Path, suffixes: set[str]) -> list[Path]:
    """Return source files with suffix filtering and shared directory excludes."""
    return [
        f for f in root.rglob("*")
        if f.is_file() and f.suffix in suffixes and not _should_skip(f)
    ]


def _read_text(path: Path) -> str:
    """Read text for heuristic scanners."""
    try:
        return path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return ""


def _line_number(content: str, offset: int) -> int:
    """Return a 1-based line number for a character offset."""
    return content.count("\n", 0, offset) + 1


def _relative_path(path_value: object, root: Path) -> str:
    """Return a stable project-relative path for JSON output."""
    if not path_value:
        return ""

    path_text = str(path_value)
    path = Path(path_text)
    if not path.is_absolute():
        return path_text

    try:
        return str(path.relative_to(root))
    except ValueError:
        return path_text


def _route_allowlist(rule: str, file_path: str) -> list[str]:
    """Return a conservative write allowlist for a routed finding."""
    if rule == "mock-only-tests":
        return ["tests/", "sanity.sh"]
    if rule == "handwritten-tests":
        return []
    if rule == "prompt-missing-review-payload":
        return [file_path, str(Path(file_path).parent / "review")]
    if file_path and file_path != ".":
        return [file_path]
    return []


def _route_dod(rule: str, file_path: str) -> dict[str, str] | None:
    """Suggest a minimal deterministic verification command for a finding."""
    if rule == "mock-only-tests":
        return {
            "command": "python -m compileall -q tests",
            "assertion": "exit_code == 0",
        }
    if file_path.endswith(".rs"):
        return {
            "command": "cargo check --workspace --all-targets",
            "assertion": "exit_code == 0",
        }
    if file_path.endswith((".ts", ".tsx", ".js", ".jsx")):
        return {
            "command": "npm run check",
            "assertion": "exit_code == 0",
        }
    if file_path.endswith(".py"):
        return {
            "command": f"python -m py_compile {file_path}",
            "assertion": "exit_code == 0",
        }
    if file_path.endswith(".sh"):
        return {
            "command": f"bash -n {file_path}",
            "assertion": "exit_code == 0",
        }
    if rule.startswith("prompt-"):
        return {
            "command": "review-prompt --dry-run with the prompt template and source context",
            "assertion": "review payload can be assembled without missing files",
        }
    return None


def _default_action(rule: str) -> dict[str, object]:
    """Build the primary action for a rule."""
    action_type, description, auto_fixable = _RULE_ACTIONS.get(
        rule,
        (
            "review-finding",
            "Review this finding and choose a project-specific remediation.",
            False,
        ),
    )
    return {
        "type": action_type,
        "auto_fixable": auto_fixable,
        "runner": _RULE_ROUTE.get(rule, "human-review"),
        "description": description,
    }


def _suppression_action(rule: str) -> dict[str, object]:
    """Build the standard suppression/documentation action."""
    return {
        "type": "suppress",
        "auto_fixable": False,
        "description": (
            f"Document why `{rule}` is acceptable for this file and add a "
            "narrow suppression only if the project owner accepts the tradeoff."
        ),
    }


def _remediation_route(rule: str, file_path: str) -> dict[str, object]:
    """Suggest the safest downstream runner for a finding."""
    runner = _RULE_ROUTE.get(rule, "human-review")
    route: dict[str, object] = {
        "runner": runner,
        "confidence": 0.72
        if runner == "code-runner"
        else 0.68
        if runner == "review-prompt"
        else 0.55,
        "reason": "Bounded finding with an executable verification path"
        if runner == "code-runner"
        else "Prompt finding should be reviewed by the prompt review loop"
        if runner == "review-prompt"
        else "Finding needs architectural judgment or human review",
    }
    allowlist = _route_allowlist(rule, file_path)
    if allowlist:
        route["allowlist"] = allowlist
    dod = _route_dod(rule, file_path)
    if dod:
        route["definition_of_done"] = dod
    return route


def _normalize_violation(
    violation: dict[str, Any],
    root: Path,
    detector: str,
) -> dict[str, Any]:
    """Add stable automation metadata to a raw violation."""
    normalized = dict(violation)
    rule = str(normalized.get("rule", "unknown"))
    file_path = _relative_path(normalized.get("file") or normalized.get("path"), root)
    if not file_path:
        file_path = "."

    line_value = normalized.get("line", 0)
    try:
        line = int(line_value or 0)
    except (TypeError, ValueError):
        line = 0

    normalized["rule"] = rule
    normalized["file"] = file_path
    normalized["line"] = line
    normalized.setdefault("severity", "warn")
    normalized.setdefault("confidence", _RULE_CONFIDENCE.get(rule, 0.60))
    normalized.setdefault(
        "finding_id",
        f"{rule}:{file_path}:{line}",
    )
    normalized.setdefault(
        "evidence",
        {
            "source": "monitor-codebase",
            "detector": detector,
        },
    )
    normalized.setdefault(
        "actions",
        [
            _default_action(rule),
            _suppression_action(rule),
        ],
    )
    normalized.setdefault("remediation_route", _remediation_route(rule, file_path))
    return normalized


# ---------------------------------------------------------------------------
# Treesitter-based checks (compose /treesitter violations)
# ---------------------------------------------------------------------------

def _run_treesitter_violations(
    root: Path,
    exclude_rules: list[str] | None = None,
) -> list[dict[str, Any]]:
    """Call /treesitter violations and return parsed results."""
    cmd = [str(TREESITTER_RUN), "violations", str(root), "--json"]
    if exclude_rules:
        cmd.extend(["--exclude-rules", ",".join(exclude_rules)])

    try:
        result = subprocess.run(
            cmd, capture_output=True, text=True, timeout=120,
            env={k: v for k, v in os.environ.items() if k != 'VIRTUAL_ENV'},
        )
        # Exit code 1 means violations found (not an error)
        if result.stdout.strip():
            return json.loads(result.stdout)
        return []
    except (subprocess.TimeoutExpired, json.JSONDecodeError, OSError) as e:
        logger.warning("treesitter violations failed: {}", e)
        return []


