def scan_project(project_path: str, include_dirs: list[str] | None = None) -> dict[str, Any]:
    """Run all quality checks against a project directory."""
    root = Path(project_path).resolve()
    if not root.is_dir():
        return {
            "schema_version": SCHEMA_VERSION,
            "error": f"Not a directory: {root}",
            "violations": [],
        }

    scan_roots = []
    if include_dirs:
        for d in include_dirs:
            p = root / d
            if p.is_dir():
                scan_roots.append(p)
    if not scan_roots:
        scan_roots = [root]

    all_violations: list[dict[str, Any]] = []

    # Determine treesitter exclusions
    # Memory project is exempt from AQL checks
    exclude_rules = None
    if root.name == "memory" or "experiments/memory" in str(root):
        exclude_rules = ["bespoke-aql", "bespoke-aql-api"]

    for scan_root in scan_roots:
        logger.info("Quality scanning: {}", scan_root)

        # AST-based checks via /treesitter violations
        ts_violations = _run_treesitter_violations(scan_root, exclude_rules)
        all_violations.extend(ts_violations)

        # File-content checks (test quality — not AST)
        all_violations.extend(_check_handwritten_tests(scan_root))
        all_violations.extend(_check_mock_only_tests(scan_root))
        all_violations.extend(_check_typescript_practices(scan_root))
        all_violations.extend(_check_rust_practices(scan_root))
        all_violations.extend(_check_prompt_practices(scan_root))

    all_violations = [
        _normalize_violation(v, root, "quality_checks.py")
        for v in all_violations
    ]

    # Group by rule
    by_rule: dict[str, int] = {}
    for v in all_violations:
        by_rule[v["rule"]] = by_rule.get(v["rule"], 0) + 1

    return {
        "schema_version": SCHEMA_VERSION,
        "project": str(root),
        "total_violations": len(all_violations),
        "by_rule": by_rule,
        "violations": all_violations,
        "languages": {
            "python": bool(_iter_py_files(root)),
            "typescript": bool(_iter_files(root, _TYPESCRIPT_SUFFIXES)),
            "rust": bool(_iter_files(root, _RUST_SUFFIXES)),
            "prompts": any(
                _is_prompt_file(path, root)
                for path in _iter_files(root, _PROMPT_SUFFIXES)
            ),
        },
    }


