import explainer from '@/proof-explainer.json';

/** "How proof works" (webgpt review, item 8): one real Tau execution — the
 *  roundtable that designed this site — walked from goal to receipt. Each stage
 *  resolves to a real immutable artifact (filename + sha256), an excerpt of the
 *  load-bearing fields, the invariant that holds across the transition, and an
 *  explicit proves / does-not-prove boundary. Server-rendered: the full
 *  explanation is in static HTML; the <details> drawer only reveals the raw
 *  field excerpt, so a reader understands the sequence without opening JSON.
 *  Generated by scripts/gen_proof_explainer.py — nothing here is authored. */

interface Stage {
  n: number;
  name: string;
  desc: string;
  artifact: string;
  digest: string;
  excerpt: Record<string, unknown>;
  invariant: string;
  proves: string;
  not: string;
}

const STAGES = explainer.stages as Stage[];

export function ProofExplainer() {
  return (
    <ol className="proofx" aria-label="How proof works: one real run from goal to receipt">
      {STAGES.map((s, i) => (
        <li key={s.n} className="proofx-stage">
          <div className="proofx-rail" aria-hidden="true">
            <span className="proofx-dot">{s.n}</span>
            {i < STAGES.length - 1 && <span className="proofx-line" />}
          </div>
          <div className="proofx-body">
            <h3 className="proofx-name">{s.name}</h3>
            <p className="proofx-desc">{s.desc}</p>
            <p className="proofx-invariant">
              <span className="proofx-tag">invariant</span>
              {s.invariant}
            </p>
            <div className="proofx-boundary">
              <p className="proofx-proves">
                <span className="proofx-tag proofx-tag--y">proves</span>
                {s.proves}
              </p>
              <p className="proofx-not">
                <span className="proofx-tag proofx-tag--n">does not prove</span>
                {s.not}
              </p>
            </div>
            <details className="proofx-drawer">
              <summary
                data-qid={`proofx:excerpt:${s.n}`}
                data-qs-action="PROOFX_TOGGLE_EXCERPT"
                title={`Inspect the source field from ${s.artifact}`}
              >
                <span className="machine">{s.artifact}</span>
                <span className="proofx-sha"> · sha256 {s.digest}…</span>
              </summary>
              <dl className="proofx-fields">
                {Object.entries(s.excerpt).map(([k, v]) => (
                  <div key={k} className="proofx-field">
                    <dt className="machine">{k}</dt>
                    <dd className="machine">
                      {typeof v === 'object' ? JSON.stringify(v) : String(v)}
                    </dd>
                  </div>
                ))}
              </dl>
            </details>
          </div>
        </li>
      ))}
    </ol>
  );
}
