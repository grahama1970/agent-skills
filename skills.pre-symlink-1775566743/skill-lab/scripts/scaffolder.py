#!/usr/bin/env python3
"""Scaffold a new skill from a composition manifest.

Generates the complete skill directory: SKILL.md, run.sh, sanity.sh,
and orchestrator wiring for HAVE skills + CREATE capabilities.

Usage:
    python scaffolder.py --manifest composition_manifest.yml --output /path/to/skill
    python scaffolder.py --manifest manifest.yml --dry-run
"""
from __future__ import annotations

import json
import os
import stat
import sys
from pathlib import Path
from textwrap import dedent

try:
    import yaml
    def _load_yaml(path: Path) -> dict:
        with open(path) as f:
            return yaml.safe_load(f) or {}
except ImportError:
    def _load_yaml(path: Path) -> dict:
        return json.loads(path.read_text())


def scaffold_skill_md(manifest: dict) -> str:
    """Generate SKILL.md content from manifest."""
    name = manifest["name"]
    task = manifest["task"]

    have_skills = [item["skill"] for item in manifest["composition"]["have"]]
    provides = []
    for item in manifest["composition"]["have"]:
        role = item.get("role", "")
        if role and role not in provides:
            provides.append(role)
    # Also add any created capabilities
    for item in manifest["composition"]["create"]:
        cap = item.get("capability", "")
        if cap and cap not in provides:
            provides.append(cap)

    provides_yaml = "\n".join(f"  - {p}" for p in provides) if provides else "  - general"
    composes_yaml = "\n".join(f"  - {s}" for s in have_skills) if have_skills else "  []"

    have_table = ""
    for item in manifest["composition"]["have"]:
        have_table += f"| `{item['skill']}` | {item.get('role', '')} | `{item.get('bond', 'run.sh')}` |\n"

    create_table = ""
    for item in manifest["composition"]["create"]:
        lab = item.get("lab") or "direct"
        create_table += f"| `{item['capability']}` | {item.get('description', '')} | `/{lab}` |\n"

    return dedent(f"""\
    ---
    name: {name}
    description: >
      {task}
    metadata:
      short-description: Auto-generated composite skill
      generated-by: skill-lab
    provides:
    {provides_yaml}
    composes:
    {composes_yaml}
    ---

    # {name}

    {task}

    ## Composition

    ### Existing Skills (HAVE)

    | Skill | Role | Bond |
    |-------|------|------|
    {have_table}
    ### Crafted Capabilities (CREATE)

    | Capability | Description | Lab |
    |-----------|-------------|-----|
    {create_table}
    ## Usage

    ```bash
    ./run.sh run
    ```

    ## Generated by /skill-lab

    This skill was auto-generated via symbiogenic composition.
    See composition_manifest.yml for the reaction equation.
    """)


def scaffold_run_sh(manifest: dict) -> str:
    """Generate run.sh orchestrator."""
    name = manifest["name"]
    steps = []

    for item in manifest["composition"]["have"]:
        skill = item["skill"]
        bond = item.get("bond", "run.sh")
        role = item.get("role", skill)
        steps.append(f"""\
    # {role}
    echo "[{name}] Running {skill}..."
    SKILL_DIR="$SKILLS_DIR/{skill}"
    if [[ -x "$SKILL_DIR/run.sh" ]]; then
        "$SKILL_DIR/run.sh" "$@"
    else
        echo "WARN: {skill} not found at $SKILL_DIR"
    fi
    """)

    steps_block = "\n".join(steps)

    return dedent(f"""\
    #!/usr/bin/env bash
    set -eo pipefail
    SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
    SKILLS_DIR="$(dirname "$SCRIPT_DIR")"

    case "${{1:-run}}" in
        run)
            echo "=== [{name}] Starting ==="
    {steps_block}
            echo "=== [{name}] Complete ==="
            ;;
        *)
            echo "Usage: $0 {{run}}"
            exit 1
            ;;
    esac
    """)


def scaffold_sanity_sh(manifest: dict) -> str:
    """Generate sanity.sh for the skill."""
    name = manifest["name"]
    checks = []

    for item in manifest["composition"]["have"]:
        skill = item["skill"]
        checks.append(f"""\
    echo -n "Check - {skill} exists: "
    if [[ -d "$SKILLS_DIR/{skill}" ]]; then
        echo "PASS"
    else
        echo "FAIL: {skill} not found"
        FAILED=1
    fi
    """)

    checks_block = "\n".join(checks)

    return dedent(f"""\
    #!/usr/bin/env bash
    set -eo pipefail
    SCRIPT_DIR="$(cd "$(dirname "${{BASH_SOURCE[0]}}")" && pwd)"
    SKILLS_DIR="$(dirname "$SCRIPT_DIR")"
    FAILED=0

    echo "=== [{name}] Sanity Check ==="

    echo -n "Check - SKILL.md exists: "
    if [[ -f "$SCRIPT_DIR/SKILL.md" ]]; then
        echo "PASS"
    else
        echo "FAIL"
        exit 1
    fi

    {checks_block}

    if [[ $FAILED -eq 1 ]]; then
        echo "Result: FAIL"
        exit 1
    fi
    echo "Result: PASS"
    """)


def scaffold_skill(manifest: dict, output_dir: Path, dry_run: bool = False):
    """Scaffold complete skill directory."""
    output_dir.mkdir(parents=True, exist_ok=True)

    files = {
        "SKILL.md": scaffold_skill_md(manifest),
        "run.sh": scaffold_run_sh(manifest),
        "sanity.sh": scaffold_sanity_sh(manifest),
    }

    # Save the manifest
    try:
        import yaml
        manifest_text = yaml.dump(manifest, default_flow_style=False, sort_keys=False)
    except ImportError:
        manifest_text = json.dumps(manifest, indent=2)
    files["composition_manifest.yml"] = manifest_text

    for filename, content in files.items():
        path = output_dir / filename
        if dry_run:
            print(f"--- {path} ---")
            print(content[:500])
            if len(content) > 500:
                print(f"... ({len(content)} chars total)")
            print()
        else:
            path.write_text(content)
            if filename.endswith(".sh"):
                path.chmod(path.stat().st_mode | stat.S_IEXEC)
            print(f"  Created: {path}")

    if not dry_run:
        print(f"\nSkill scaffolded at: {output_dir}")
        print(f"Next steps:")
        print(f"  1. Review and customize run.sh")
        print(f"  2. Craft CREATE capabilities via lab skills")
        print(f"  3. Run: python validate.py {output_dir}")
        print(f"  4. Run: bash {output_dir}/sanity.sh")


import typer
from typing import Optional

app = typer.Typer(help="Scaffold a skill from manifest")


@app.callback(invoke_without_command=True)
def main(
    manifest: str = typer.Option(..., help="Path to composition manifest"),
    output: Optional[str] = typer.Option(None, help="Output directory (default: .pi/skills/<name>)"),
    dry_run: bool = typer.Option(False, "--dry-run", help="Preview without writing"),
) -> None:
    """Scaffold a skill from a composition manifest."""
    manifest_data = _load_yaml(Path(manifest))

    if output:
        output_dir = Path(output)
    else:
        output_dir = Path(__file__).parent.parent.parent / manifest_data["name"]

    scaffold_skill(manifest_data, output_dir, dry_run=dry_run)


if __name__ == "__main__":
    app()
