# Scan: hardcoded skill paths
# ---------------------------------------------------------------------------

def scan_hardcoded_skill_paths(skill_dir: Path) -> List[Violation]:
    """Detect hardcoded ~/.pi/skills/ paths that break in non-standard layouts.

    Rules:
    - subprocess.hardcoded_skill_path: use SKILLS_DIR env var instead.
    """
    violations: List[Violation] = []
    skill_name = skill_dir.name

    _PATH_EXEMPT = {"skills-ci", "skills-broadcast", "skill-lab"}
    if skill_name in _PATH_EXEMPT:
        return violations

    for py_file in iter_python_files(skill_dir):
        try:
            text = py_file.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue

        if re.search(r'["\']~?/\.pi/skills/|HOME.*\.pi/skills|home/.*\.pi/skills', text):
            violations.append(Violation(
                rule="subprocess.hardcoded_skill_path",
                severity="warn",
                skill=skill_name,
                path=str(py_file),
                message="Hardcoded ~/.pi/skills/ path — use SKILLS_DIR env var with fallback.",
            ))
            break

    for sh_file in skill_dir.rglob("*.sh"):
        if should_skip_path(sh_file):
            continue
        try:
            text = sh_file.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue

        if re.search(r'\$HOME/\.pi/skills/|~/\.pi/skills/', text):
            if "SKILLS_DIR" not in text:
                violations.append(Violation(
                    rule="subprocess.hardcoded_skill_path",
                    severity="warn",
                    skill=skill_name,
                    path=str(sh_file),
                    message="Hardcoded ~/.pi/skills/ path — use ${SKILLS_DIR:-$HOME/.pi/skills}.",
                ))
                break

    return violations


# ---------------------------------------------------------------------------
# Scan: mock-only tests (no integration)
# ---------------------------------------------------------------------------

def scan_mock_only_tests(skill_dir: Path) -> List[Violation]:
    """Detect skills where ALL tests use mocks with no integration tests.

    Rules:
    - testing.mock_only: every test uses mocks, no sanity.sh exists.
    """
    violations: List[Violation] = []
    skill_name = skill_dir.name

    _MOCK_EXEMPT = {"test-lab", "skills-ci", "eval-skills"}
    if skill_name in _MOCK_EXEMPT:
        return violations

    test_files = [f for f in skill_dir.rglob("test_*.py") if not should_skip_path(f)]
    if not test_files:
        return violations

    has_sanity = (skill_dir / "sanity.sh").exists()
    all_mocked = True

    for test_file in test_files:
        try:
            content = test_file.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue

        uses_mock = any(p in content for p in [
            "unittest.mock", "MagicMock", "AsyncMock", "@patch", "mock.patch",
        ])
        if not uses_mock:
            all_mocked = False
            break

    if all_mocked and not has_sanity:
        violations.append(Violation(
            rule="testing.mock_only",
            severity="warn",
            skill=skill_name,
            path=str(skill_dir),
            message="All tests use mocks but no sanity.sh — mocked tests pass while real service may be broken.",
        ))

    return violations
