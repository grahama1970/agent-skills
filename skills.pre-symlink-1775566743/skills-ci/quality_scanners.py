# ---------------------------------------------------------------------------
# Scan: AQL in shell scripts
# ---------------------------------------------------------------------------

def scan_shell_aql(skill_dir: Path) -> List[Violation]:
    """Detect raw AQL queries in shell scripts.

    Rules:
    - subprocess.shell_aql: AQL in .sh files — must use /memory endpoints.

    The AQL keyword regex matches per-line (no DOTALL) to avoid false
    positives from Python ``for x in y`` loops inside heredocs.  Lines
    containing ``# skills-ci-exempt: shell_aql`` are skipped.
    """
    violations: List[Violation] = []
    skill_name = skill_dir.name

    _AQL_EXCEPTIONS = {"monitor-memory", "ops-arango", "monitor-personas"}
    if skill_name in _AQL_EXCEPTIONS:
        return violations

    # AQL pattern: FOR <var> IN <collection> ... FILTER/RETURN/COLLECT/SORT
    # on a single line.  Case-sensitive FOR/IN to avoid matching Python/bash.
    _AQL_LINE_RE = re.compile(
        r"FOR\s+\w+\s+IN\s+\w+.*(?:FILTER|RETURN|COLLECT|SORT)"
    )
    _EXEMPT_RE = re.compile(r"#\s*skills-ci-exempt:\s*shell_aql")

    for sh_file in skill_dir.rglob("*.sh"):
        if should_skip_path(sh_file):
            continue
        try:
            text = sh_file.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue

        # Check for file-level exemption (anywhere in the file)
        if _EXEMPT_RE.search(text):
            continue

        # Per-line AQL keyword check (case-sensitive — AQL uses uppercase)
        for line in text.splitlines():
            if _EXEMPT_RE.search(line):
                continue
            if _AQL_LINE_RE.search(line):
                violations.append(Violation(
                    rule="subprocess.shell_aql",
                    severity="warn",
                    skill=skill_name,
                    path=str(sh_file),
                    message="Shell script contains AQL query — use /memory skill endpoints instead.",
                ))
                break  # one violation per file is enough

        if re.search(r"arangosh|_api/cursor|_api/gharial", text):
            violations.append(Violation(
                rule="subprocess.shell_aql",
                severity="warn",
                skill=skill_name,
                path=str(sh_file),
                message="Shell script calls ArangoDB API directly — use /memory skill endpoints.",
            ))

    return violations


# ---------------------------------------------------------------------------
# Scan: SKILL.md bloat
# ---------------------------------------------------------------------------

_SKILLMD_WARN_LINES = 500


def scan_skill_md_length(skill_dir: Path) -> List[Violation]:
    """Detect bloated SKILL.md files that should be split.

    Rules:
    - skills.skill_md_bloat: SKILL.md > 500 lines. Move rules to best-practices-*.
    """
    violations: List[Violation] = []
    skill_md = skill_dir / "SKILL.md"

    if not skill_md.exists():
        return violations

    try:
        line_count = len(skill_md.read_text(encoding="utf-8", errors="ignore").splitlines())
    except Exception:
        return violations

    if line_count > _SKILLMD_WARN_LINES:
        violations.append(Violation(
            rule="skills.skill_md_bloat",
            severity="warn",
            skill=skill_dir.name,
            path=str(skill_md),
            message=f"SKILL.md is {line_count} lines (limit {_SKILLMD_WARN_LINES}). Move rules to best-practices-* skill.",
        ))

    return violations


