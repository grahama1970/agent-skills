"""Quality enforcement scanners for skills-ci.

Detects violations of prompt hygiene, blind test requirements,
regex-as-classifier anti-patterns, and AQL in shell scripts.

Composes /treesitter violations for AST-based checks (inline prompts,
regex classifiers). File-content checks remain here.

Split from scanners.py to stay under 800-line limit.
"""
from __future__ import annotations

import os

import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, List

_THIS_DIR = str(Path(__file__).resolve().parent)
if _THIS_DIR not in sys.path:
    sys.path.insert(0, _THIS_DIR)

from models import Violation
from scanners import iter_python_files, should_skip_path

# Resolve /treesitter run.sh path
_SKILLS_DIR = Path(__file__).resolve().parent.parent
_TREESITTER_RUN = _SKILLS_DIR / "treesitter" / "run.sh"


def _run_treesitter_violations(
    skill_dir: Path,
    rules: list[str],
) -> list[dict[str, Any]]:
    """Call /treesitter violations for specific rules and return parsed results."""
    cmd = [
        str(_TREESITTER_RUN), "violations", str(skill_dir),
        "--rules", ",".join(rules), "--json",
    ]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, timeout=60,
            env={k: v for k, v in os.environ.items() if k != 'VIRTUAL_ENV'},
        )
        if result.stdout.strip():
            return json.loads(result.stdout)
        return []
    except (subprocess.TimeoutExpired, json.JSONDecodeError, OSError):
        return []


# Skills that ARE prompt management tools — exempt from inline prompt detection
_PROMPT_EXEMPT_SKILLS = {
    "prompt-lab", "scillm", "assistant", "create-gpt", "train-convo-steering",
}


def scan_prompt_hygiene(skill_dir: Path) -> List[Violation]:
    """Detect inline LLM prompts in Python files via /treesitter violations.

    Rules:
    - prompt.inline_prompt: string containing LLM prompt patterns.
      Should use /prompt-lab for versioning and evaluation.
    """
    skill_name = skill_dir.name
    if skill_name in _PROMPT_EXEMPT_SKILLS:
        return []

    violations: List[Violation] = []
    for v in _run_treesitter_violations(skill_dir, ["inline-prompt"]):
        file_path = Path(v.get("file", str(skill_dir)))
        if should_skip_path(file_path):
            continue
        violations.append(Violation(
            rule="prompt.inline_prompt",
            severity="error",
            skill=skill_name,
            path=v.get("file", str(skill_dir)),
            message=v.get("message", "Inline LLM prompt — use /prompt-lab"),
        ))
    return violations


# ---------------------------------------------------------------------------
# Scan: blind test enforcement
# ---------------------------------------------------------------------------

_TEST_EXEMPT_SKILLS = {
    "test-lab", "skills-ci", "eval-skills",  # meta-testing tools
}


def scan_blind_test_enforcement(skill_dir: Path) -> List[Violation]:
    """Check that skills use /test-lab for blind adversarial testing.

    Rules:
    - testing.no_blind_tests: skill has Python code but no tests at all
    - testing.handwritten_tests: test_*.py files without test-lab markers
    """
    violations: List[Violation] = []
    skill_name = skill_dir.name

    if skill_name in _TEST_EXEMPT_SKILLS:
        return violations

    test_files = [f for f in skill_dir.rglob("test_*.py") if not should_skip_path(f)]
    has_sanity = (skill_dir / "sanity.sh").exists()

    if not test_files and not has_sanity:
        py_files = list(iter_python_files(skill_dir))
        if len(py_files) > 1:  # more than just __init__.py
            violations.append(Violation(
                rule="testing.no_blind_tests",
                severity="warn",
                skill=skill_name,
                path=str(skill_dir),
                message="Skill has Python code but no tests or sanity.sh — add /test-lab blind tests.",
            ))
        return violations

    for test_file in test_files:
        try:
            content = test_file.read_text(encoding="utf-8", errors="ignore")
        except Exception:
            continue

        is_test_lab = any(marker in content for marker in [
            "test-lab", "test_lab", "blind evaluation", "adversarial", "Generated by",
        ])

        if not is_test_lab:
            violations.append(Violation(
                rule="testing.handwritten_tests",
                severity="warn",
                skill=skill_name,
                path=str(test_file),
                message="Test file appears handwritten (no test-lab markers) — agents can game their own tests. Use /test-lab generate.",
                fixable=True,
            ))

    return violations


