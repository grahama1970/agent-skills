"""Generate synthetic PDFs from detected failure patterns.

Creates small (~6 page) PDFs that reproduce specific extraction challenges
so convergence can be measured against known structure.
"""

from __future__ import annotations

import json
import random
from dataclasses import dataclass, field, asdict
from pathlib import Path
from typing import Any, Dict, List, Optional

from loguru import logger

try:
    from reportlab.lib.pagesizes import letter, A4
    from reportlab.lib.units import inch, cm
    from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
    from reportlab.platypus import (
        SimpleDocTemplate,
        Paragraph,
        Spacer,
        Table,
        TableStyle,
        PageBreak,
        Image,
        KeepTogether,
    )
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT, TA_CENTER, TA_JUSTIFY

    HAS_REPORTLAB = True
except ImportError:
    HAS_REPORTLAB = False

# Load pattern recipes
_RECIPES_PATH = Path(__file__).parent.parent / "data" / "pattern_recipes.json"


@dataclass
class SyntheticSpec:
    """Known structure of the generated synthetic PDF."""

    sections: int = 0
    tables: int = 0
    figures: int = 0
    pages: int = 0
    patterns_reproduced: List[str] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


def _load_recipes() -> Dict[str, Any]:
    """Load pattern recipes from JSON."""
    if _RECIPES_PATH.exists():
        return json.loads(_RECIPES_PATH.read_text())
    return {}


def generate_synthetic(
    patterns: List[str],
    target_sections: int = 8,
    target_tables: int = 2,
    target_figures: int = 1,
    output_path: Optional[Path] = None,
) -> tuple[Path, SyntheticSpec]:
    """Generate a synthetic PDF reproducing the given patterns.

    Args:
        patterns: List of pattern names (e.g., ["multi_column", "split_tables"])
        target_sections: How many sections to create
        target_tables: How many tables to create
        target_figures: How many figure placeholders
        output_path: Where to save the PDF (default: temp file)

    Returns:
        (pdf_path, spec) — the generated PDF and its known structure
    """
    if not HAS_REPORTLAB:
        raise ImportError("reportlab is required for synthetic PDF generation")

    if output_path is None:
        import tempfile
        fd = tempfile.NamedTemporaryFile(suffix=".pdf", prefix="pdf_lab_synthetic_", delete=False)
        output_path = Path(fd.name)
        fd.close()

    output_path.parent.mkdir(parents=True, exist_ok=True)
    recipes = _load_recipes()

    # Build document
    doc = SimpleDocTemplate(
        str(output_path),
        pagesize=letter,
        rightMargin=0.75 * inch,
        leftMargin=0.75 * inch,
        topMargin=0.75 * inch,
        bottomMargin=0.75 * inch,
    )

    styles = getSampleStyleSheet()
    story: List[Any] = []

    # Track actual structure
    actual_sections = 0
    actual_tables = 0
    actual_figures = 0

    # Title page
    story.append(Paragraph("Synthetic Extraction Test Document", styles["Title"]))
    story.append(Spacer(1, 0.3 * inch))
    story.append(
        Paragraph(
            f"Patterns: {', '.join(patterns)}<br/>"
            f"Generated by pdf-lab for convergence testing",
            styles["Normal"],
        )
    )
    story.append(PageBreak())

    # Generate sections with pattern-specific content
    for i in range(1, target_sections + 1):
        section_content = _build_section(
            i, patterns, recipes, styles, target_tables, target_figures,
            actual_tables, actual_figures,
        )
        story.extend(section_content["elements"])
        actual_sections += 1
        actual_tables += section_content["tables_added"]
        actual_figures += section_content["figures_added"]

        # Add page break between some sections for multi-page testing
        if i % 3 == 0 and i < target_sections:
            story.append(PageBreak())

    # Build the PDF
    try:
        doc.build(story)
    except Exception as e:
        logger.error(f"Failed to build synthetic PDF: {e}")
        raise

    # Estimate pages (title + ~2 sections per page)
    estimated_pages = 1 + max(1, (actual_sections + 1) // 2)

    spec = SyntheticSpec(
        sections=actual_sections,
        tables=actual_tables,
        figures=actual_figures,
        pages=estimated_pages,
        patterns_reproduced=patterns,
    )

    logger.info(
        f"Generated synthetic PDF: {output_path} "
        f"({actual_sections} sections, {actual_tables} tables, {actual_figures} figures)"
    )

    return output_path, spec


def _build_section(
    section_num: int,
    patterns: List[str],
    recipes: Dict[str, Any],
    styles: Any,
    target_tables: int,
    target_figures: int,
    tables_so_far: int,
    figures_so_far: int,
) -> Dict[str, Any]:
    """Build a section with pattern-appropriate content."""
    elements: List[Any] = []
    tables_added = 0
    figures_added = 0

    # Section header
    header_style = _get_header_style(patterns, styles, section_num)
    elements.append(Paragraph(f"{section_num}. Section {section_num} Title", header_style))
    elements.append(Spacer(1, 0.15 * inch))

    # Body text
    body_text = _generate_body_text(patterns, section_num)
    elements.append(Paragraph(body_text, styles["Normal"]))
    elements.append(Spacer(1, 0.1 * inch))

    # Add multi-column simulation if pattern present
    if "multi_column" in patterns and section_num % 2 == 0:
        col_text = _generate_column_text()
        elements.append(Paragraph(col_text, styles["Normal"]))
        elements.append(Spacer(1, 0.1 * inch))

    # Add table if needed
    if tables_so_far < target_tables and section_num % max(1, target_tables) == 0:
        table = _build_table(patterns, section_num)
        elements.append(table)
        elements.append(Spacer(1, 0.15 * inch))
        tables_added = 1

    # Add figure placeholder if needed (distribute evenly across sections)
    if figures_so_far < target_figures and section_num % max(1, target_figures) == 0:
        fig_text = f"[Figure {figures_so_far + 1}: Placeholder diagram for pattern testing]"
        elements.append(
            Paragraph(fig_text, ParagraphStyle("FigCaption", parent=styles["Normal"], alignment=TA_CENTER))
        )
        elements.append(Spacer(1, 0.1 * inch))
        figures_added = 1

    # Add citation-like noise if testing citation filters
    if "citation_noise" in patterns or section_num == 3:
        elements.append(
            Paragraph(
                "[1] A. Author, B. Writer. Journal of Testing, 2024. pp. 100-115.",
                styles["Normal"],
            )
        )

    return {
        "elements": elements,
        "tables_added": tables_added,
        "figures_added": figures_added,
    }


def _get_header_style(patterns: List[str], styles: Any, section_num: int) -> Any:
    """Get header style — vary font size based on patterns."""
    base = styles["Heading1"]

    if "section_undersegmentation" in patterns:
        # Use smaller font that might be missed by high thresholds
        return ParagraphStyle(
            f"SmallHeader_{section_num}",
            parent=base,
            fontSize=10,
            leading=12,
            spaceAfter=6,
        )
    elif "section_oversegmentation" in patterns:
        # Use varied sizes that might cause false positives
        size = random.choice([11, 12, 13, 14])
        return ParagraphStyle(
            f"VarHeader_{section_num}",
            parent=base,
            fontSize=size,
            leading=size + 2,
            spaceAfter=6,
        )
    return base


def _generate_body_text(patterns: List[str], section_num: int) -> str:
    """Generate body text appropriate for the patterns being tested."""
    base_text = (
        f"This is the body content for section {section_num}. "
        "It contains multiple sentences to simulate real document text. "
        "The extraction pipeline should correctly identify this as body content "
        "and not confuse it with section headers or table data. "
    )

    if "multi_column" in patterns:
        # Add short lines that simulate column breaks
        base_text += (
            "Column analysis requires careful handling of text reflow. "
            "Short lines may indicate column boundaries. "
            "The extractor must merge these correctly."
        )

    if "scanned_no_ocr" in patterns:
        # Add text that might have OCR artifacts
        base_text += (
            "Scanned documents often contain OCR artifacts like l1gatures, "
            "misread characters (rn vs m), and spacing issues."
        )

    return base_text


def _generate_column_text() -> str:
    """Generate text that simulates multi-column layout challenges."""
    return (
        "Left column content here. | Right column content there. "
        "Column merging is a known challenge for PDF extractors. "
        "When columns are not detected, text from different columns "
        "gets interleaved, creating nonsensical output."
    )


def _build_table(patterns: List[str], section_num: int) -> Table:
    """Build a table appropriate for the patterns being tested."""
    if "split_tables" in patterns:
        # Large table that might span pages
        data = [["Header A", "Header B", "Header C", "Header D"]]
        for row in range(12):
            data.append([
                f"Cell {row+1}-A",
                f"Value {random.randint(100, 999)}",
                f"Data {row+1}",
                f"Result {random.uniform(0.1, 9.9):.2f}",
            ])
    elif "missed_tables" in patterns:
        # Table with thin lines that might be missed with wrong line_scale
        data = [["ID", "Name", "Value"]]
        for row in range(5):
            data.append([str(row + 1), f"Item {row + 1}", f"{random.randint(1, 100)}"])
    else:
        # Standard table
        data = [
            ["Parameter", "Value", "Unit"],
            ["Temperature", "25.0", "C"],
            ["Pressure", "1.013", "bar"],
            ["Flow Rate", "150", "L/min"],
        ]

    table = Table(data)
    style_cmds = [
        ("BACKGROUND", (0, 0), (-1, 0), colors.grey),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.whitesmoke),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, 0), 10),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 8),
        ("BACKGROUND", (0, 1), (-1, -1), colors.beige),
        ("GRID", (0, 0), (-1, -1), 1, colors.black),
    ]

    if "missed_tables" in patterns:
        # Thin lines — harder to detect with high line_scale
        style_cmds[-1] = ("GRID", (0, 0), (-1, -1), 0.25, colors.grey)

    table.setStyle(TableStyle(style_cmds))
    return table
